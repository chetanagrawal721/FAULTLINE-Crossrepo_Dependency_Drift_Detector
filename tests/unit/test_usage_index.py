D = {"pkg", "yaml"}

# --- TC-6.3.1: re-export, wildcard, alias, shadowing, notebook, plus the other constructs of master 20.3 -------------------------
FILES = {
    "app/__init__.py": b"from .models import *\nfrom .shim import Thing as ReExported\n",
    "app/models.py": (b"import pkg\n__all__ = ['Model']\nclass Model(pkg.Base):\n    def go(self):\n        return self.validate() + self.local()\n"
                      b"    def local(self):\n        return 1\n"),
    "app/shim.py": b"from pkg.mod import Thing\n",
    "app/use.py": (b"import pkg\nimport pkg.sub as s\nfrom pkg.mod import Thing as T\nfrom pkg import *\nimport yaml\n\n"
                   b"def f(yaml, name):\n"                         # `yaml` here is a parameter: it shadows the import
                   b"    x = pkg.Cls(1)\n    x.method(a=2)\n"
                   b"    yaml.load('a')\n"
                   b"    return T(3), s.run(), getattr(pkg, 'lit'), getattr(pkg, name), 'pkg.mod:Thing'\n\n"
                   b"def g():\n    from app import ReExported\n    return ReExported(1)\n"),
    "app/generated_pb2.py": b"# Generated by the protocol buffer compiler. DO NOT EDIT!\nimport pkg\npkg.proto.Message()\n",
    "app/optional.py": b"try:\n    import yaml\nexcept ImportError:\n    yaml = None\nfrom typing import TYPE_CHECKING\nif TYPE_CHECKING:\n    import pkg\n",
    "app/broken.py": b"def (:\n",
    "notes/analysis.ipynb": json.dumps({"cells": [{"cell_type": "markdown", "source": ["# t"]},
                                                  {"cell_type": "code", "source": ["%matplotlib inline\n", "import pkg\n", "pkg.plot(1)\n"]}]}).encode(),
}
EXPORTS = {"pkg": (["Alpha", "Beta"], True)}


def rows(idx, path):
    return [(r.line, r.kind, r.target, r.status, r.flags) for r in idx.refs if r.file == path]


def test_tc_6_3_1_statuses_match_the_golden_file():
    idx = build_index(FILES, D, exports=EXPORTS)
    assert rows(idx, "app/use.py") == [
        (1, "IMPORT", "pkg", "RESOLVED", ()),
        (2, "IMPORT", "pkg.sub", "RESOLVED", ()),
        (3, "IMPORT", "pkg.mod.Thing", "RESOLVED", ()),
        (4, "IMPORT", "pkg.Alpha", "RESOLVED", ()),                                      # wildcard expanded with __all__ of the target
        (4, "IMPORT", "pkg.Beta", "RESOLVED", ()),
        (5, "IMPORT", "yaml", "RESOLVED", ()),
        (8, "CALL", "pkg.Cls", "RESOLVED", ()),                                          # `x = pkg.Cls(1)`
        (9, "CALL", "pkg.Cls.method", "RESOLVED", ()),                                   # local type propagation: x.method() is Cls.method
        (11, "CALL", "pkg.mod.Thing", "RESOLVED", ()),                                   # from-import alias
        (11, "CALL", "pkg.sub.run", "RESOLVED", ()),                                     # module alias
        (11, "ATTRIBUTE", "pkg.lit", "RESOLVED", ()),                                         # getattr with a literal name is an attribute access
        (11, "DYNAMIC", "pkg", "DYNAMIC", ()),                                           # getattr with a computed name
        (11, "STRING", "pkg.mod.Thing", "LOW_CONFIDENCE", ()),                           # a dotted string path
        (14, "IMPORT", "pkg.mod.Thing", "RESOLVED", ()),                                 # `from app import ReExported` is followed through app/__init__ and app/shim
        (15, "CALL", "pkg.mod.Thing", "RESOLVED", ()),
    ]                                                                                    # note: yaml.load on line 10 is the parameter, not the import
    assert rows(idx, "app/models.py") == [
        (1, "IMPORT", "pkg", "RESOLVED", ()),
        (3, "BASE", "pkg.Base", "RESOLVED", ()),                                         # class Model(pkg.Base)
        (5, "CALL", "pkg.Base.validate", "LOW_CONFIDENCE", ()),                          # self.validate() is inherited from the base; self.local() is not
    ]
    assert rows(idx, "app/optional.py") == [(2, "IMPORT", "yaml", "RESOLVED", ("OPTIONAL_PATH",)), (7, "IMPORT", "pkg", "RESOLVED", ("TYPE_ONLY",))]
    assert rows(idx, "app/generated_pb2.py") == [(2, "IMPORT", "pkg", "RESOLVED", ("GENERATED",)), (3, "CALL", "pkg.proto.Message", "RESOLVED", ("GENERATED",))]
    assert rows(idx, "notes/analysis.ipynb") == [(2, "IMPORT", "pkg", "RESOLVED", ("NOTEBOOK",)), (3, "CALL", "pkg.plot", "RESOLVED", ("NOTEBOOK",))]
    assert rows(idx, "app/broken.py") == [(1, "PARSE_ERROR", None, "UNRESOLVED", ())] and idx.failed_files == ["app/broken.py"]


def test_a_star_import_without_known_names_is_unresolved_not_absent():
    idx = build_index({"a.py": b"from pkg import *\n"}, D)
    assert [(r.kind, r.status) for r in idx.refs] == [("WILDCARD", "UNRESOLVED")]
    low = build_index({"a.py": b"from pkg import *\nAlpha()\n"}, D, exports={"pkg": (["Alpha"], False)})        # names known, but not from __all__
    assert [(r.target, r.status) for r in low.refs if r.kind == "CALL"] == [("pkg.Alpha", "LOW_CONFIDENCE")]


def test_namespace_mutation_patching_and_entry_points():
    src = (b"import pkg, importlib\nfrom unittest import mock\n"
           b"pkg.hook = 1\nsetattr(pkg, 'x', 2)\nmock.patch('pkg.mod.func')\nimportlib.import_module('pkg.plugins')\nimportlib.import_module(name)\nexec(code)\n")
    idx = build_index({"a.py": src, "app_ep.py": b"def main(): pass\n"}, D, entry_points=["pkg.cli:main", "app_ep:main"])
    kinds = [(r.line, r.kind, r.status) for r in idx.refs if r.file == "a.py"]
    assert (3, "NAMESPACE_MUTATION", "DYNAMIC") in kinds and (4, "NAMESPACE_MUTATION", "DYNAMIC") in kinds and (5, "NAMESPACE_MUTATION", "DYNAMIC") in kinds
    assert (6, "IMPORT", "RESOLVED") in kinds and (7, "DYNAMIC", "DYNAMIC") in kinds and (8, "EXEC", "UNRESOLVED") in kinds
    assert [r.target for r in idx.refs if r.kind == "ENTRY_POINT"] == ["pkg.cli.main"]                  # an entry point inside the artifact is not a divergent reference


def test_tc_6_3_2_coverage_is_computed_and_the_dynamic_reference_is_listed():
    src = b"import pkg\n" + b"".join(f"pkg.f{i}()\n".encode() for i in range(8)) + b"getattr(pkg, name)\n"      # 1 import + 8 calls resolved, 1 dynamic
    idx = build_index({"a.py": src}, D)
    cov = idx.coverage()
    assert (cov.resolved, cov.total) == (9, 10) and cov.ratio == 0.9 and cov.text() == "9/10 references (90.0%)"
    assert [(r.line, r.kind) for r in cov.unresolved] == [(10, "DYNAMIC")]
    assert build_index({"a.py": b"x = 1\n"}, D).coverage().ratio == 1.0                                  # no references: nothing is hidden, coverage is complete
    eval_ref = build_index({"a.py": b"import pkg\neval(s)\n"}, D).coverage()
    assert (eval_ref.resolved, eval_ref.total) == (1, 2)                                                  # eval cannot be attributed, and it still counts against coverage


def test_tc_6_3_3_editing_one_file_reanalyses_only_that_file():
    cache = UsageCache()
    first = build_index(FILES, D, cache=cache, exports=EXPORTS)
    n = len([p for p in FILES if p.endswith((".py", ".ipynb"))])
    assert first.analyzed == n and cache.misses == n and cache.hits == 0
    again = build_index(FILES, D, cache=cache, exports=EXPORTS)
    assert again.analyzed == 0 and cache.hits == n and again.refs == first.refs
    edited = {**FILES, "app/shim.py": FILES["app/shim.py"] + b"# changed\n"}
    third = build_index(edited, D, cache=cache, exports=EXPORTS)
    assert third.analyzed == 1                                                                           # only app/shim.py


def test_the_index_reads_source_and_never_runs_it(tmp_path):
    marker = tmp_path / "ran"
    idx = build_index({"a.py": f"import pkg\nopen({str(marker)!r}, 'w').write('x')\npkg.f()\n".encode()}, D)
    assert not marker.exists() and [r.target for r in idx.refs if r.kind == "CALL"] == ["pkg.f"]


# --- exposure --------------------------------------------------------------------------------------------------------------------
OLD = {"pkg/__init__.py": b"from .retry import Retry\n", "pkg/retry.py": b"class Retry:\n    def __init__(self, total=1, method_whitelist=None, backoff=0): pass\n"
                                                                    b"def keep(a, b=1): pass\ndef gone(): pass\n"}
NEW = {"pkg/__init__.py": b"from .retry import Retry\n", "pkg/retry.py": b"class Retry:\n    def __init__(self, total=1, allowed_methods=None, backoff=0): pass\n"
                                                                    b"def keep(a, b=1): pass\n"}


def test_exposure_intersects_references_with_the_delta_and_simulates_binding():
    delta = compute_delta(extract(OLD, "pkg"), extract(NEW, "pkg"))
    src = (b"from pkg.retry import Retry, keep, gone\n"
           b"Retry(total=3, method_whitelist=['GET'])\nRetry(total=3, allowed_methods=['GET'])\nRetry(*args)\nkeep(1)\n")
    res = compute_exposure(build_index({"a.py": src}, {"pkg"}), {"pkg": delta})
    by = {(e.ref.line, e.change.symbol): e.static_ok for e in res.exposures}
    assert by[(2, "pkg.retry.Retry")] is False                                                           # method_whitelist no longer binds
    assert by[(3, "pkg.retry.Retry")] is True                                                            # allowed_methods binds
    assert by[(4, "pkg.retry.Retry")] is None                                                            # star arguments: unknown
    assert by[(1, "pkg.retry.gone")] is False                                                            # importing a removed symbol
    assert not any(e.change.symbol == "pkg.retry.keep" for e in res.exposures)                           # unchanged
    assert not any(e.ref.kind == "IMPORT" and e.change.symbol == "pkg.retry.Retry" for e in res.exposures)  # an import of a changed signature is not a use of it
    assert {e.ref.line for e in res.breaking_exposures} == {1, 2, 4}                                     # the call that binds is cleared
    ev = res.evidence_fields()
    assert ev["api_delta_breaking"] is True and ev["static_confirmed"] is True and len(ev["exposures"]) == 3
    assert ev["coverage"] == 1.0 and ev["dynamic_refs"] is False


def test_no_delta_means_nothing_is_claimed():
    idx = build_index({"a.py": b"import pkg\npkg.f()\n"}, {"pkg"})
    ev = compute_exposure(idx, {}).evidence_fields()
    assert ev["api_delta_breaking"] is None and ev["exposures"] is None and ev["static_limits"] == ("pkg: no API delta was computed",)


def test_simulate_bind_follows_inspect_signature_bind():
    import inspect

    def f(a, b=1, /, c=2, *args, d, e=5, **kw): ...
    import ast

    from faultline.diff.surface import _params
    params = _params(ast.parse("def f(a, b=1, /, c=2, *args, d, e=5, **kw): pass").body[0].args, False)
    for n_pos, kws in [(1, ["d"]), (0, ["d"]), (2, ["c", "d"]), (3, ["d"]), (5, ["d"]), (1, ["d", "zzz"]), (1, ["a", "d"]), (1, [])]:
        try:
            inspect.signature(f).bind(*range(n_pos), **{k: 0 for k in kws})
            expect = True
        except TypeError:
            expect = False
        assert simulate_bind({"n_pos": n_pos, "kw": kws, "star": False, "dstar": False}, params) is expect, (n_pos, kws)
