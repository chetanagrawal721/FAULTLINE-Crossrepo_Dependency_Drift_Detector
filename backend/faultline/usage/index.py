def _notebook_source(raw: bytes) -> str | None:
    try:
        nb = json.loads(raw.decode("utf-8"))
        cells = [c for c in nb.get("cells", []) if c.get("cell_type") == "code"]
    except (ValueError, AttributeError):
        return None
    out = []
    for c in cells:
        src = c.get("source", "")
        src = "".join(src) if isinstance(src, list) else str(src)
        out.append("\n".join(("# " + ln) if ln.lstrip().startswith(("%", "!")) else ln for ln in src.split("\n")))
    return "\n".join(out)


def analyze_file(path: str, raw: bytes, divergent: set[str], internal: set[str], exports: dict | None = None) -> FileFacts:
    sha = content_hash(raw)
    module = module_of(path) if not path.endswith(".ipynb") else ""
    facts = FileFacts(path, sha, module)
    tags: list[str] = []
    if path.endswith(".ipynb"):
        text = _notebook_source(raw)
        tags.append("NOTEBOOK")
    else:
        text = raw.decode("utf-8", "replace")
    if path.endswith(("_pb2.py", "_pb2_grpc.py")) or (text and any(GENERATED.search(ln) for ln in text.split("\n")[:8])):
        tags.append("GENERATED")
    try:
        tree = ast.parse(text or "")
    except (SyntaxError, ValueError, RecursionError):
        facts.refs.append(Reference(path, sha, 1, 0, "PARSE_ERROR", None, None, "UNRESOLVED", tuple(tags), reason="the file does not parse, so its references are unknown"))
        return facts
    is_init = path.endswith("__init__.py")
    col = _Collector(module, is_init, divergent, internal, exports or {})
    col.visit(tree)
    uses = _Uses(path, sha, col, divergent, internal, tuple(tags))
    for node, target, tg, status in col.imports:
        uses.add(node, "IMPORT", target, status, tags=tg)
    for node, mod, tg in col.wild_unknown:
        uses.add(node, "WILDCARD", mod, "UNRESOLVED", tags=tg, reason=f"`from {mod} import *` and the names it brings in are not known")
    uses.visit(tree)
    facts.refs += uses.refs
    facts.aliases = {n: a.target for n, a in col.alias.items()}
    facts.wildcards = col.wildcards
    return facts


