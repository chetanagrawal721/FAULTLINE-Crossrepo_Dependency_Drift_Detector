def _chase(target: str, mods: dict[str, FileFacts], depth: int = 0) -> str | None:
    """Follow a name through the artifact's own modules (re-exports, aliases, wildcards) until it leaves the artifact."""
    parts = target.split(".")
    for i in range(len(parts), 0, -1):
        prefix = ".".join(parts[:i])
        if prefix in mods:
            break
    else:
        return target
    if depth >= MAX_CHASE or i == len(parts):
        return None                                                    # the module itself, or a cycle: not a reference to a divergent symbol
    facts, rest = mods[prefix], parts[i:]
    if rest[0] in facts.aliases:
        return _chase(".".join([facts.aliases[rest[0]], *rest[1:]]), mods, depth + 1)
    for w in facts.wildcards:
        got = _chase(f"{w}.{'.'.join(rest)}", mods, depth + 1)
        if got and got != f"{w}.{'.'.join(rest)}":
            return got
    return None


def build_index(files: dict[str, bytes], divergent: set[str], *, cache: UsageCache | None = None, exports: dict | None = None,
                entry_points: list[str] | None = None) -> UsageIndex:
    """`files`: {path: bytes} of the artifact's sources (.py and .ipynb). `exports`: {module: (public names, taken from __all__)} for
    star imports from divergent packages. `entry_points`: "pkg.mod:attr" strings from package metadata."""
    paths = sorted(p for p in files if p.endswith((".py", ".ipynb")))
    modules = {module_of(p) for p in paths if p.endswith(".py")}
    internal = {m.split(".")[0] for m in modules if m} - set(divergent)
    exp_key = object_hash(sorted((k, sorted(v[0]) if v[0] is not None else None, v[1]) for k, v in (exports or {}).items()))
    idx = UsageIndex(frozenset(divergent))
    facts: dict[str, FileFacts] = {}
    for p in paths:
        key = object_hash([content_hash(files[p]), p, ANALYZER_VERSION, sorted(divergent), sorted(internal), exp_key])
        if cache is not None and key in cache.store:
            f = cache.store[key]
            cache.hits += 1
        else:
            f = analyze_file(p, files[p], divergent, internal, exports)
            idx.analyzed += 1
            if cache is not None:
                cache.store[key] = f
                cache.misses += 1
        facts[p] = f
        if any(r.kind == "PARSE_ERROR" for r in f.refs):
            idx.failed_files.append(p)
    mods = {f.module: f for f in facts.values() if f.module and f.path.endswith(".py")}
    for p in paths:
        for r in facts[p].refs:
            if r.target is None or r.package in divergent:
                idx.refs.append(r)
                continue
            final = _chase(r.target, mods)
            if final and _root(final) in divergent:
                idx.refs.append(Reference(r.file, r.file_sha256, r.line, r.col, r.kind, final, _root(final), r.status, r.flags, r.shape, r.reason))
    for ep in entry_points or []:
        t = ep.replace(":", ".")
        final = _chase(t, mods)
        if final and _root(final) in divergent:
            idx.refs.append(Reference("<entry-points>", "", 0, 0, "ENTRY_POINT", final, _root(final), "RESOLVED", reason=f"entry point {ep}"))
    idx.refs.sort(key=lambda r: (r.file, r.line, r.col, r.kind))
    return idx


def persist_index(conn, index: UsageIndex, files: dict[str, bytes]) -> int:
    """Store usage_file per content hash and one usage_ref per reference (same tables as the call-site extractor)."""
    for p, raw in files.items():
        if p.endswith((".py", ".ipynb")):
            bad = p in index.failed_files
            conn.execute("INSERT OR REPLACE INTO usage_file(content_hash, analyzer_version, status) VALUES (?,?,?)",
                         (content_hash(raw), ANALYZER_VERSION, "PARSE_ERROR" if bad else "OK"))
    n = 0
    for r in index.refs:
        if not r.file_sha256:
            continue
        conn.execute("INSERT OR REPLACE INTO usage_ref(id, content_hash, line, col, target, root_package, status, ref_kind, call_shape_json, tags) "
                     "VALUES (?,?,?,?,?,?,?,?,?,?)",
                     ("ur_" + object_hash([r.file_sha256, r.line, r.col, r.target, r.status, r.kind])[:24], r.file_sha256, r.line, r.col, r.target,
                      r.package, r.status, r.kind, json.dumps(r.shape, sort_keys=True) if r.shape else None, ",".join(r.flags)))
        n += 1
    return n
