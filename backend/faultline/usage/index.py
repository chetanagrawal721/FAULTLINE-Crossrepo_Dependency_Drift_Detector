"""Full usage index (M6.3, master section 20.3): every reference an artifact's source makes into the divergent packages D.

Source is parsed, never imported or run. Each reference gets a status:
  RESOLVED        the fully qualified target is known
  LOW_CONFIDENCE  the target was inferred (a reassigned variable, `self.x` on a class with a known base, a dotted string, a wildcard
                  import from a module without `__all__`)
  DYNAMIC         the target depends on runtime values (`getattr(pkg, name)`, `import_module(name)`, patching `pkg.x`)
  UNRESOLVED      the analysis could not tell (`exec`, `eval`, a file that does not parse, a wildcard with unknown names)
Dynamic and unresolved references are kept and counted; they are never treated as absent. They lower coverage.

Analysis is in two phases so that it can be cached per file: phase 1 reads one file (keyed by its content hash) and phase 2 follows
re-exports through the artifact's own modules.

Limits, on purpose: a name rebound at module level does not shadow an import (only function-local names do); type propagation is
flow-insensitive; methods reached through containers, return values of artifact functions and metaclass machinery are not followed.
"""
import ast
import json
import re
from dataclasses import dataclass, field
from pathlib import PurePosixPath

from ..core.hashing import content_hash, object_hash

ANALYZER_VERSION = "usage/2"
RESOLVED_STATUSES = ("RESOLVED", "LOW_CONFIDENCE", "OBSERVED")
DYNAMIC_IMPORTERS = {"importlib.import_module", "__import__"}
DOTTED = re.compile(r"^[A-Za-z_]\w*(\.[A-Za-z_]\w*)+(:[A-Za-z_][\w.]*)?$")
GENERATED = re.compile(r"auto-?generated|generated by|do not edit|@generated", re.I)
MAX_CHASE = 6


@dataclass(frozen=True)
class Reference:
    file: str
    file_sha256: str
    line: int
    col: int
    kind: str                       # IMPORT | CALL | ATTRIBUTE | NAME | BASE | STRING | NAMESPACE_MUTATION | DYNAMIC | EXEC | PARSE_ERROR | WILDCARD | ENTRY_POINT
    target: str | None
    package: str | None             # import root of the target (None: the reference could not be attributed to a package)
    status: str
    flags: tuple[str, ...] = ()     # TYPE_ONLY, OPTIONAL_PATH, GENERATED, NOTEBOOK, WILDCARD_NO_ALL
    shape: dict | None = None       # CALL: {"n_pos", "kw", "star", "dstar"}
    reason: str | None = None

    @property
    def ref_id(self) -> str:
        return f"{self.file}:{self.line}:{self.col}"

    def to_json(self) -> dict:
        return {"id": self.ref_id, "kind": self.kind, "target": self.target, "package": self.package, "status": self.status,
                "flags": list(self.flags), "shape": self.shape, "reason": self.reason}


@dataclass
class FileFacts:
    """What one file says, before re-exports through the artifact's own modules are followed."""
    path: str
    sha: str
    module: str
    refs: list[Reference] = field(default_factory=list)
    aliases: dict[str, str] = field(default_factory=dict)          # module-level binding -> dotted target
    wildcards: list[str] = field(default_factory=list)             # modules star-imported from inside the artifact


@dataclass(frozen=True)
class Coverage:
    resolved: int
    total: int
    unresolved: tuple[Reference, ...]

    @property
    def ratio(self) -> float:
        return 1.0 if self.total == 0 else self.resolved / self.total

    def text(self) -> str:
        return f"{self.resolved}/{self.total} references ({self.ratio * 100:.1f}%)"


@dataclass
class UsageIndex:
    divergent: frozenset[str]
    refs: list[Reference] = field(default_factory=list)
    failed_files: list[str] = field(default_factory=list)
    analyzed: int = 0                                              # files analysed in this build (the rest came from the cache)

    def refs_to_divergent(self) -> list[Reference]:
        """Master 21.1: every reference, of any status, whose import root is divergent, plus those that cannot be attributed."""
        return [r for r in self.refs if (r.package in self.divergent) or (r.package is None and r.status in ("DYNAMIC", "UNRESOLVED"))]

    def coverage(self) -> Coverage:
        rs = self.refs_to_divergent()
        ok = [r for r in rs if r.status in RESOLVED_STATUSES]
        return Coverage(len(ok), len(rs), tuple(r for r in rs if r.status not in RESOLVED_STATUSES))


class UsageCache:
    """Per-file results keyed by content hash and by everything else that could change them. A hit costs no analysis."""

    def __init__(self) -> None:
        self.store: dict[str, FileFacts] = {}
        self.hits = 0
        self.misses = 0


# ------------------------------------------------------------------------------------------------ helpers

def module_of(path: str) -> str:
    p = PurePosixPath(path)
    parts = list(p.with_suffix("").parts)
    if parts and parts[0] == "src":
        parts = parts[1:]
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _dotted(node: ast.AST) -> str | None:
    parts = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    return ".".join(reversed([*parts, node.id])) if isinstance(node, ast.Name) else None


def _root(t: str | None) -> str | None:
    return t.split(".")[0] if t else None


def _shape(call: ast.Call) -> dict:
    return {"n_pos": sum(1 for a in call.args if not isinstance(a, ast.Starred)), "kw": [k.arg for k in call.keywords if k.arg],
            "star": any(isinstance(a, ast.Starred) for a in call.args), "dstar": any(k.arg is None for k in call.keywords)}


def _relative(module: str, is_init: bool, level: int, name: str | None) -> str | None:
    parts = module.split(".") if module else []
    base = parts if is_init else parts[:-1]
    if level - 1 > max(len(base) - 0, 0):
        return None
    base = base[: len(base) - (level - 1)] if level > 1 else base
    return ".".join([*base, *([name] if name else [])]) or None


@dataclass
class _Alias:
    target: str
    tags: frozenset[str] = frozenset()
    low: bool = False


class _Collector(ast.NodeVisitor):
    """Every import in the file (function-level ones too) with the kind of block it sits in."""

    def __init__(self, module: str, is_init: bool, divergent: set[str], internal: set[str], exports: dict) -> None:
        self.module, self.is_init, self.D, self.internal, self.exports = module, is_init, divergent, internal, exports
        self.alias: dict[str, _Alias] = {}
        self.imports: list[tuple[ast.AST, str, frozenset[str], str]] = []      # (node, target, tags, status)
        self.wildcards: list[str] = []
        self.wild_unknown: list[tuple[ast.AST, str, frozenset[str]]] = []
        self._ctx: list[str] = []

    def _bind(self, name: str, target: str, node: ast.AST, low: bool = False) -> None:
        tags = frozenset(self._ctx)
        if name in self.alias and self.alias[name].target != target:
            low = True                                                     # the same name is bound to two different things
        self.alias.setdefault(name, _Alias(target, tags, low))
        if _root(target) in self.D or _root(target) in self.internal:
            self.imports.append((node, target, tags, "LOW_CONFIDENCE" if low else "RESOLVED"))

    def visit_Import(self, node: ast.Import) -> None:
        for a in node.names:
            if a.asname:
                self._bind(a.asname, a.name, node)
            else:
                self._bind(a.name.split(".")[0], a.name.split(".")[0], node)
                if "." in a.name and _root(a.name) in self.D | self.internal:
                    self.imports.append((node, a.name, frozenset(self._ctx), "RESOLVED"))

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        mod = _relative(self.module, self.is_init, node.level, node.module) if node.level else node.module
        if not mod:
            return
        for a in node.names:
            if a.name == "*":
                if _root(mod) in self.internal:
                    self.wildcards.append(mod)
                elif _root(mod) in self.D:
                    names, from_all = self.exports.get(mod, (None, False))
                    if names is None:
                        self.wild_unknown.append((node, mod, frozenset(self._ctx)))
                    else:
                        for n in names:
                            self._bind(n, f"{mod}.{n}", node, low=not from_all)
                continue
            self._bind(a.asname or a.name, f"{mod}.{a.name}", node)

    def visit_If(self, node: ast.If) -> None:
        if (_dotted(node.test) or "").endswith("TYPE_CHECKING"):
            self._ctx.append("TYPE_ONLY")
            for n in node.body:
                self.visit(n)
            self._ctx.pop()
            for n in node.orelse:
                self.visit(n)
        else:
            self.generic_visit(node)

    def visit_Try(self, node: ast.Try) -> None:
        def names(t):
            return {e.id for e in (t.elts if isinstance(t, ast.Tuple) else [t]) if isinstance(e, ast.Name)} if t is not None else set()
        guarded = any(names(h.type) & {"ImportError", "ModuleNotFoundError"} for h in node.handlers)
        if guarded:
            self._ctx.append("OPTIONAL_PATH")
        for n in node.body:
            self.visit(n)
        if guarded:
            self._ctx.pop()
        for part in (node.handlers, node.orelse, node.finalbody):
            for n in part:
                self.visit(n)


def _scope_bindings(body: list[ast.stmt], params: set[str]) -> tuple[dict[str, int], dict[str, list[ast.AST]]]:
    """Names bound inside one function scope (not its nested functions) with how often, and the values assigned by calls."""
    counts: dict[str, int] = {p: 1 for p in params}
    calls: dict[str, list[ast.AST]] = {}

    def bind(t: ast.AST, value: ast.AST | None = None) -> None:
        if isinstance(t, ast.Name):
            counts[t.id] = counts.get(t.id, 0) + 1
            if isinstance(value, ast.Call):
                calls.setdefault(t.id, []).append(value.func)
            else:
                calls.setdefault(t.id, []).append(ast.Constant(value=None))          # a non-call assignment spoils the type
        elif isinstance(t, (ast.Tuple, ast.List)):
            for e in t.elts:
                bind(e)

    def walk(nodes):
        for n in nodes:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                counts[n.name] = counts.get(n.name, 0) + 1
                continue
            if isinstance(n, ast.Assign):
                for t in n.targets:
                    bind(t, n.value if len(n.targets) == 1 else None)
            elif isinstance(n, ast.AnnAssign):
                bind(n.target, n.value)
            elif isinstance(n, ast.AugAssign):
                bind(n.target)
            elif isinstance(n, (ast.For, ast.AsyncFor)):
                bind(n.target)
            elif isinstance(n, (ast.With, ast.AsyncWith)):
                for it in n.items:
                    if it.optional_vars is not None:
                        bind(it.optional_vars)
            elif isinstance(n, ast.ExceptHandler) and n.name:
                counts[n.name] = counts.get(n.name, 0) + 1
            for field_name in ("body", "orelse", "finalbody", "handlers"):
                if hasattr(n, field_name) and isinstance(getattr(n, field_name), list):
                    walk(getattr(n, field_name))
            if isinstance(n, ast.Expr) or isinstance(n, ast.Return):
                continue
            for sub in ast.iter_child_nodes(n):
                if isinstance(sub, ast.NamedExpr):
                    bind(sub.target, sub.value)

    walk(body)
    return counts, calls


@dataclass
class _Scope:
    kind: str                                                      # function | class
    locals: set[str] = field(default_factory=set)
    types: dict[str, tuple[str, bool]] = field(default_factory=dict)
    base: str | None = None
    class_names: set[str] = field(default_factory=set)


class _Uses(ast.NodeVisitor):
    def __init__(self, path: str, sha: str, collector: _Collector, divergent: set[str], internal: set[str], tags: tuple[str, ...]) -> None:
        self.path, self.sha, self.c, self.D, self.internal = path, sha, collector, divergent, internal
        self.file_tags = tags
        self.refs: list[Reference] = []
        self.scopes: list[_Scope] = []
        self.class_bases: dict[str, str] = {}
        self._skip: set[int] = set()

    # -- reference creation -------------------------------------------------------------------------------------
    def _wanted(self, target: str | None) -> bool:
        return bool(target) and (_root(target) in self.D or _root(target) in self.internal)

    def add(self, node: ast.AST, kind: str, target: str | None, status: str, *, tags=(), shape=None, reason=None, package="auto") -> None:
        pkg = _root(target) if package == "auto" else package
        self.refs.append(Reference(self.path, self.sha, node.lineno, node.col_offset, kind, target, pkg, status,
                                   tuple(sorted({*tags, *self.file_tags})), shape, reason))

    # -- name resolution ----------------------------------------------------------------------------------------
    def head(self, name: str):
        for s in reversed(self.scopes):
            if s.kind == "function":
                if name in s.types:
                    return "typed", s.types[name]
                if name in s.locals:
                    return None                                         # a parameter or local variable shadows the import
        if name in self.class_bases:
            return "base", self.class_bases[name]
        if name in self.c.alias:
            return "alias", self.c.alias[name]
        return None

    def resolve(self, node: ast.AST) -> tuple[str, str, frozenset[str]] | None:
        """(target, status, tags) for a Name, attribute chain, `getattr(x, "lit")`, `super().x`, `self.x`, or `X(...).attr`."""
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "getattr" and len(node.args) == 2 \
                and isinstance(node.args[1], ast.Constant) and isinstance(node.args[1].value, str):
            b = self.resolve(node.args[0])
            return (f"{b[0]}.{node.args[1].value}", b[1], b[2]) if b else None
        if isinstance(node, ast.Attribute):
            v = node.value
            if isinstance(v, ast.Call) and isinstance(v.func, ast.Name) and v.func.id == "super" and self._base():
                return f"{self._base()}.{node.attr}", "LOW_CONFIDENCE", frozenset()
            if isinstance(v, ast.Call):
                inner = self.resolve(v.func)
                return (f"{inner[0]}.{node.attr}", "LOW_CONFIDENCE", inner[2]) if inner else None
            b = self.resolve(v)
            return (f"{b[0]}.{node.attr}", b[1], b[2]) if b else self._self_attr(node)
        if isinstance(node, ast.Name):
            h = self.head(node.id)
            if h is None:
                return None
            kind, val = h
            if kind == "alias":
                return val.target, "LOW_CONFIDENCE" if val.low else "RESOLVED", val.tags
            if kind == "typed":
                return val[0], "LOW_CONFIDENCE" if val[1] else "RESOLVED", frozenset()
            return val, "RESOLVED", frozenset()
        return None

    def _base(self) -> str | None:
        return next((s.base for s in reversed(self.scopes) if s.kind == "class" and s.base), None)

    def _self_attr(self, node: ast.Attribute) -> tuple[str, str, frozenset[str]] | None:
        if isinstance(node.value, ast.Name) and node.value.id in ("self", "cls"):
            cls = next((s for s in reversed(self.scopes) if s.kind == "class"), None)
            if cls and cls.base and node.attr not in cls.class_names:
                return f"{cls.base}.{node.attr}", "LOW_CONFIDENCE", frozenset()
        return None

    # -- visitors -----------------------------------------------------------------------------------------------
    def _function(self, node) -> None:
        for d in node.decorator_list:
            self.visit(d)
        a = node.args
        for dflt in [*a.defaults, *[d for d in a.kw_defaults if d is not None]]:
            self.visit(dflt)
        for arg in [*a.posonlyargs, *a.args, *a.kwonlyargs, a.vararg, a.kwarg]:
            if arg is not None and arg.annotation is not None:
                self.visit(arg.annotation)
        if getattr(node, "returns", None) is not None:
            self.visit(node.returns)
        params = {x.arg for x in [*a.posonlyargs, *a.args, *a.kwonlyargs, a.vararg, a.kwarg] if x is not None}
        scope = _Scope("function")
        body = node.body if isinstance(node.body, list) else []
        counts, calls = _scope_bindings(body, params)
        scope.locals = set(counts)
        self.scopes.append(scope)
        for name, funcs in calls.items():
            found = {r[0] for r in (self.resolve(f) for f in funcs) if r and self._wanted(r[0])}
            if len(found) == 1 and all(isinstance(f, (ast.Name, ast.Attribute, ast.Call)) for f in funcs) and name not in params:
                scope.types[name] = (found.pop(), counts[name] > 1)
        if isinstance(node.body, list):
            self._skip_docstring(node.body)
            for st in node.body:
                self.visit(st)
        else:
            self.visit(node.body)
        self.scopes.pop()

    visit_FunctionDef = visit_AsyncFunctionDef = _function

    def visit_Lambda(self, node: ast.Lambda) -> None:
        self._function(node)

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        for d in node.decorator_list:
            self.visit(d)
        base = None
        for b in node.bases:
            r = self.resolve(b)
            if r and self._wanted(r[0]):
                self.add(b, "BASE", r[0], r[1], tags=r[2])
                base = base or r[0]
            else:
                self.visit(b)
        for k in node.keywords:
            self.visit(k.value)
        if base:
            self.class_bases[node.name] = base
        names = {n.name for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))}
        names |= {t.id for n in node.body if isinstance(n, ast.Assign) for t in n.targets if isinstance(t, ast.Name)}
        self.scopes.append(_Scope("class", base=base, class_names=names))
        self._skip_docstring(node.body)
        for st in node.body:
            self.visit(st)
        self.scopes.pop()

    def _skip_docstring(self, body: list[ast.stmt]) -> None:
        if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
            self._skip.add(id(body[0].value))

    def visit_Module(self, node: ast.Module) -> None:
        self._skip_docstring(node.body)
        self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        r = self.resolve(node)
        if r and self._wanted(r[0]) and isinstance(node.ctx, ast.Load):
            self.add(node, "ATTRIBUTE", r[0], r[1], tags=r[2])
            return
        self.generic_visit(node)

    def visit_Name(self, node: ast.Name) -> None:
        if isinstance(node.ctx, ast.Load):
            r = self.resolve(node)
            if r and self._wanted(r[0]) and ("." in r[0]) and not (node.id in self.c.alias and self.c.alias[node.id].target == node.id):
                self.add(node, "NAME", r[0], r[1], tags=r[2])

    def visit_Constant(self, node: ast.Constant) -> None:
        if isinstance(node.value, str) and id(node) not in self._skip and DOTTED.match(node.value):
            target = node.value.replace(":", ".")
            if _root(target) in self.D:
                self.add(node, "STRING", target, "LOW_CONFIDENCE", reason="a dotted string whose prefix is a divergent package")

    def _mutation(self, node: ast.AST, target_node: ast.AST) -> bool:
        r = self.resolve(target_node)
        if r and self._wanted(r[0]):
            self.add(node, "NAMESPACE_MUTATION", r[0], "DYNAMIC", tags=r[2], reason=f"{r[0]} is assigned to or deleted at runtime")
            return True
        return False

    def visit_Assign(self, node: ast.Assign) -> None:
        for t in node.targets:
            if isinstance(t, ast.Attribute):
                self._mutation(node, t)
        self.visit(node.value)
        for t in node.targets:
            if not isinstance(t, (ast.Name, ast.Attribute)):
                self.visit(t)

    def visit_AugAssign(self, node: ast.AugAssign) -> None:
        if isinstance(node.target, ast.Attribute):
            self._mutation(node, node.target)
        self.visit(node.value)

    def visit_Delete(self, node: ast.Delete) -> None:
        for t in node.targets:
            if isinstance(t, ast.Attribute):
                self._mutation(node, t)

    def visit_Call(self, node: ast.Call) -> None:
        f = node.func
        fname = f.id if isinstance(f, ast.Name) else None
        dotted = _dotted(f) or ""
        if fname in ("exec", "eval") and self.head(fname) is None:
            self.add(node, "EXEC", None, "UNRESOLVED", package=None, reason=f"{fname}() runs code that cannot be read statically")
        elif fname == "getattr" and len(node.args) >= 2 and self.head("getattr") is None:
            base = self.resolve(node.args[0])
            lit = isinstance(node.args[1], ast.Constant) and isinstance(node.args[1].value, str)
            if base and self._wanted(base[0]) and not lit:
                self.add(node, "DYNAMIC", base[0], "DYNAMIC", tags=base[2], reason=f"getattr on {base[0]} with a name that is not a literal")
                return self._rest(node)
            if base and self._wanted(base[0]) and lit and len(node.args) == 2:
                self.add(node, "ATTRIBUTE", f"{base[0]}.{node.args[1].value}", base[1], tags=base[2])
                return
        elif fname == "setattr" and node.args:
            if self._mutation(node, node.args[0]):
                return self._rest(node)
        elif dotted in DYNAMIC_IMPORTERS or fname == "__import__" or dotted.endswith(".import_module"):
            a0 = node.args[0] if node.args else None
            if isinstance(a0, ast.Constant) and isinstance(a0.value, str):
                if _root(a0.value) in self.D:
                    self.add(node, "IMPORT", a0.value, "RESOLVED", reason="import by literal name")
            else:
                self.add(node, "DYNAMIC", None, "DYNAMIC", package=None, reason="import by a name that is not a literal")
            return self._rest(node)
        elif dotted.endswith(".setattr") or dotted.endswith("patch") or dotted.endswith("patch.object"):
            a0 = node.args[0] if node.args else None
            if isinstance(a0, ast.Constant) and isinstance(a0.value, str) and _root(a0.value) in self.D:
                self.add(node, "NAMESPACE_MUTATION", a0.value, "DYNAMIC", reason=f"{a0.value} is patched at runtime")
                return self._rest(node)
            if a0 is not None and self._mutation(node, a0):
                return self._rest(node)
        r = self.resolve(f)
        if r and self._wanted(r[0]):
            self.add(node, "CALL", r[0], r[1], tags=r[2], shape=_shape(node))
            return self._rest(node)
        self.generic_visit(node)

    def _rest(self, node: ast.Call) -> None:
        for a in node.args:
            self.visit(a)
        for k in node.keywords:
            self.visit(k.value)


